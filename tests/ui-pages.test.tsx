it('幅に応じた段階と表示個数を監視結果から選ぶ', () => {
    let width = 150;
    vi.spyOn(HTMLElement.prototype, 'clientWidth', 'get').mockImplementation(() => width);
    vi.spyOn(HTMLElement.prototype, 'offsetWidth', 'get').mockImplementation(function (this: HTMLElement) { return this.textContent === '長い' ? 200 : 100; });
    function Count() { const { ref, slots } = useFitCount(50, 'width'); return <div ref={ref} className="count">{slots}</div>; }
    render(<div style={{ padding: '0px' }}><FitBar steps={['長い', '短い']}>{(text, measuring) => <span className={measuring ? 'copy' : 'shown'}>{text}</span>}</FitBar><Count /></div>);
    expect(el('.shown').textContent).toBe('短い');
    expect(el('.count').textContent).toBe('3');
    width = 250;
    resize();
    frame();
    expect(el('.shown').textContent).toBe('長い');
    expect(el('.count').textContent).toBe('5');
});
