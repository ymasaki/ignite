it('コピーは原文を渡し、成功と失敗を通知し、コードの表示は原文を保つ', async () => {
    const write = vi.fn().mockResolvedValue(undefined);
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: write } });
    render(<><CopyText text="a@example.com" label="アドレス"/><Code>const</Code><CodeBlock code={'const 名前 = 1\n// 次'} language="ts" title="a.ts" lineNumbers maxLines={2}/></>);
    click('.copytext');
    await act(async () => { await Promise.resolve(); });
    expect(write).toHaveBeenCalledWith('a@example.com');
    expect(el('.copytext').classList.contains('copied')).toBe(true);
    advance(1500);
    expect(el('.copytext').classList.contains('copied')).toBe(false);
    click('.cb button');
    await act(async () => { await Promise.resolve(); });
    expect(write).toHaveBeenLastCalledWith('const 名前 = 1\n// 次');
    expect(el('pre').textContent).toBe('const 名前 = 1\n// 次\n');
    write.mockRejectedValueOnce(new Error('拒否'));
    click('.copytext');
    await act(async () => { await Promise.resolve(); });
    advance(0);
    advance(60);
    expect(el('[aria-live]').textContent).toBe('コピーできませんでした');
});
