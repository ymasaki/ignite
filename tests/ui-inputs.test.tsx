// @vitest-environment jsdom
import { useState } from 'react';
import { expect, it, vi } from 'vitest';
import { Checkbox, RadioGroup, Switch, NumberField, Combobox } from '../src/ui/Form';
import { FormField } from '../src/ui/Field';
import { TextArea, TextField, PasswordField } from '../src/ui/TextArea';
import { OtpField } from '../src/ui/OtpField';
import { Scrubber } from '../src/ui/Scrubber';
import { SearchSuggest } from '../src/ui/Search';
import { DataTable } from '../src/ui/Table';
import { domSetup, render, el, event, click, input, key, frame, host } from './dom';
domSetup();
it('見出し・補足・検証エラーを入力と結び、入力内容を通知する', () => {
    const change = vi.fn();
    render(<FormField label="名前" hint="姓名" error="必須です" required><TextField value="" onChange={change}/></FormField>);
    const field = el<HTMLInputElement>('input');
    expect(el<HTMLLabelElement>('label').htmlFor).toBe(field.id);
    expect(field.getAttribute('aria-invalid')).toBe('true');
    expect(field.getAttribute('aria-required')).toBe('true');
    expect(field.getAttribute('aria-describedby')!.split(' ').map(id => document.getElementById(id)!.textContent)).toEqual(['姓名', '必須です']);
    input('input', '山田');
    expect(change).toHaveBeenLastCalledWith('山田');
    render(<TextArea label="メモ" value="" onChange={change} maxLength={20} rows={2}/>);
    input('textarea', '記録');
    expect(change).toHaveBeenLastCalledWith('記録');
    expect(el<HTMLTextAreaElement>('textarea').maxLength).toBe(20);
});
it('パスワードの表示を切り替え、フォーム送信で伏せ直す', () => {
    const change = vi.fn();
    render(<form><PasswordField label="鍵" value="abc" onChange={change}/></form>);
    expect(el<HTMLInputElement>('input').type).toBe('password');
    click('button');
    expect(el<HTMLInputElement>('input').type).toBe('text');
    input('input', 'def');
    expect(change).toHaveBeenCalledWith('def');
    event(el('form'), 'submit');
    expect(el<HTMLInputElement>('input').type).toBe('password');
});
it('チェックの中間状態・ラジオの無効・switchの入切を通知する', () => {
    const change = vi.fn();
    render(<><Checkbox label="項目" checked={false} indeterminate onChange={change}/><RadioGroup label="選択" value="a" options={[{ value: 'a', label: 'A' }, { value: 'b', label: 'B' }, { value: 'c', label: 'C', disabled: true }]} onChange={change}/><Switch label="通知" checked={false} onChange={change}/></>);
    expect(el<HTMLInputElement>('[type=checkbox]').indeterminate).toBe(true);
    click('[type=checkbox]');
    expect(change).toHaveBeenLastCalledWith(true);
    click('[value=b]');
    expect(change).toHaveBeenLastCalledWith('b');
    change.mockClear();
    click('[value=c]');
    expect(change).not.toHaveBeenCalled();
    click('[role=switch]');
    expect(change).toHaveBeenLastCalledWith(true);
});
it('数値欄は全角入力を確定し、上下限・矢印・IMEを区別する', () => {
    const change = vi.fn();
    function Field() { const [value, set] = useState<number | null>(1); return <NumberField label="量" value={value} onChange={v => { set(v); change(v); }} min={0} max={2} step={0.1} unit="kg"/>; }
    render(<Field />);
    input('input', '３');
    expect(el('input').getAttribute('aria-valuenow')).toBe('3');
    key('input', 'Enter');
    expect(change).toHaveBeenLastCalledWith(2);
    expect(el<HTMLButtonElement>('[aria-label="量を増やす"]').disabled).toBe(true);
    key('input', 'ArrowDown');
    expect(change).toHaveBeenLastCalledWith(1.9);
    input('input', '０．５');
    key('input', 'ArrowUp');
    expect(change).toHaveBeenLastCalledWith(0.6);
    change.mockClear();
    key('input', 'Enter', { isComposing: true });
    expect(change).not.toHaveBeenCalled();
    input('input', '文字');
    event(el('input'), 'focusout');
    expect(change).toHaveBeenLastCalledWith(null);
    click('[aria-label="量を増やす"]');
    expect(change).toHaveBeenLastCalledWith(0.1);
});
