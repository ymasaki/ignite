it('確認コードは全角・余分な文字を正規化して完了通知する', () => {
    const change = vi.fn(), complete = vi.fn();
    function Code() { const [v, set] = useState(''); return <OtpField label="コード" length={4} value={v} onChange={v => { set(v); change(v); }} onComplete={complete}/>; }
    render(<Code />);
    event(el('input'), 'focusin');
    input('input', '１２ a３４５');
    frame();
    expect(change).toHaveBeenLastCalledWith('1234');
    expect(complete).toHaveBeenCalledExactlyOnceWith('1234');
    expect(document.querySelectorAll('.otp-cell.filled')).toHaveLength(4);
    click('input');
    frame();
    expect(el<HTMLInputElement>('input').selectionStart).toBe(4);
    event(el('input'), 'focusout');
    expect(el('.otp').classList.contains('focus')).toBe(false);
});
it('Comboboxは絞り込み・循環選択・変換確定・選択解除を区別する', () => {
    const change = vi.fn();
    const options = [{ value: 'a', label: 'Alpha' }, { value: 'b', label: 'Beta', meta: 2, lead: 'B' }];
    function Combo() { const [v, set] = useState<string | null>('a'); return <Combobox label="候補" value={v} options={options} onChange={v => { set(v); change(v); }}/>; }
    render(<Combo />);
    click('input');
    expect(el('input').getAttribute('aria-expanded')).toBe('true');
    key('input', 'ArrowUp');
    expect(el('[role=option].on').textContent).toContain('Beta');
    key('input', 'Enter', { keyCode: 229 });
    expect(change).not.toHaveBeenCalled();
    key('input', 'Enter');
    expect(change).toHaveBeenLastCalledWith('b');
    input('input', 'zzz');
    expect(el('.combo-empty').textContent).toBe('該当なし');
    key('input', 'Escape');
    expect(el<HTMLInputElement>('input').value).toBe('Beta');
    input('input', '');
    event(el('input'), 'focusout');
    expect(change).toHaveBeenLastCalledWith(null);
    key('input', 'ArrowDown');
    click('[role=option]');
    expect(change).toHaveBeenLastCalledWith('a');
});
it('検索候補はキーボード選択と追加検索を通知し、候補だけをEscで閉じる', () => {
    const select = vi.fn(), more = vi.fn(), change = vi.fn();
    const groups = [{ key: 'g', label: '人', items: [{ key: 'a', title: '山田', reading: 'やまだ' }, { key: 'b', title: '山本', reading: 'やまもと' }] }];
    render(<SearchSuggest label="検索" placeholder="人で絞り込み" value="山" onChange={change} groups={groups} onSelect={select} more={{ label: 'ほかも探す', onSelect: more }}/>);
    event(el('input'), 'focusin');
    expect(document.querySelectorAll('[role=option]')).toHaveLength(3);
    key('input', 'ArrowUp');
    key('input', 'Enter');
    expect(more).toHaveBeenCalledOnce();
    expect(el('input').getAttribute('aria-expanded')).toBe('true');
    key('input', 'ArrowDown');
    key('input', 'Enter');
    expect(select).toHaveBeenLastCalledWith(groups[0].items[0]);
    expect(el('input').getAttribute('aria-expanded')).toBe('false');
    key('input', 'ArrowDown');
    expect(key('input', 'Escape').defaultPrevented).toBe(true);
    input('input', '山本');
    expect(change).toHaveBeenCalledWith('山本');
    event(document.body, 'pointerdown');
    expect(el('input').getAttribute('aria-expanded')).toBe('false');
});
it('帯の数値をキーとポインタで変更し、ドラッグ解除と上限を守る', () => {
    const change = vi.fn();
    render(<Scrubber label="音量" value={50} min={0} max={100} step={5} ticks={4} onChange={change}/>);
    key('[role=slider]', 'ArrowRight');
    expect(change).toHaveBeenLastCalledWith(55);
    key('[role=slider]', 'PageDown');
    expect(change).toHaveBeenLastCalledWith(0);
    key('[role=slider]', 'End');
    expect(change).toHaveBeenLastCalledWith(100);
    const slider = el('[role=slider]');
    vi.spyOn(slider, 'getBoundingClientRect').mockReturnValue({ left: 0, width: 200 } as DOMRect);
    event(slider, 'pointerdown', { button: 0, pointerId: 1, clientX: 50 });
    expect(change).toHaveBeenLastCalledWith(25);
    event(slider, 'pointermove', { clientX: 500 });
    expect(change).toHaveBeenLastCalledWith(100);
    event(slider, 'pointercancel');
    expect(slider.classList.contains('drag')).toBe(false);
    change.mockClear();
    event(slider, 'pointermove', { clientX: 1 });
    expect(change).not.toHaveBeenCalled();
});
it('表の選択・全選択・並べ替えを通知し、空と読込中の状態を区別する', () => {
    const select = vi.fn(), sort = vi.fn();
    const rows = [[{ content: 'A' }, { content: 5, ratio: 0.5 }], [{ content: 'B' }, { content: 2, ratio: 1 }]];
    render(<DataTable label="一覧" columns={[{ label: '名前', sortable: true }, '数']} rows={rows} rowKeys={['a', 'b']} selected={['a']} onSelect={select} onSort={sort} sort={{ column: 0, dir: 'desc' }} stickyHead depths={[0, 1]}/>);
    expect(el('th[aria-sort]').getAttribute('aria-sort')).toBe('descending');
    click('.th-sort');
    expect(sort).toHaveBeenCalledWith(0);
    click('tbody input');
    expect(select).toHaveBeenLastCalledWith([]);
    click('thead input');
    expect(select).toHaveBeenLastCalledWith(['a', 'b']);
    expect(host.textContent).toContain('第2階層');
    expect(document.querySelector('.heat-2')).not.toBeNull();
    render(<DataTable label="一覧" columns={['名前']} rows={[]} empty="データなし"/>);
    expect(host.textContent).toContain('データなし');
    render(<DataTable label="一覧" columns={['名前']} rows={rows} loading/>);
    expect(el('table').getAttribute('aria-busy')).toBe('true');
    expect(document.querySelector('[role=status]')).not.toBeNull();
});
