it('Popoverは外側・Escape・子のcloseで閉じ、Escapeで元へ戻る', () => {
    render(<Popover trigger={(open, toggle) => <button aria-expanded={open} onClick={toggle}>開く</button>}>{close => <button className="close" onClick={close}>確定</button>}</Popover>);
    click('button');
    expect(document.querySelector('.popover-body')).not.toBeNull();
    event(document, 'keydown', { key: 'Escape' });
    expect(document.querySelector('.popover-body')).toBeNull();
    expect(document.activeElement).toBe(el('button'));
    click('button');
    click('.close');
    expect(document.querySelector('.popover-body')).toBeNull();
    click('button');
    event(document.body, 'pointerdown');
    expect(document.querySelector('.popover-body')).toBeNull();
});
