it('読み上げは最後の通知を使い、Dialogの開閉に合わせて置き場所を選ぶ', () => {
    announce('古い');
    announce('新しい', { assertive: true });
    advance(0);
    advance(60);
    expect(el('[aria-live]').textContent).toBe('新しい');
    expect(el('[aria-live]').getAttribute('aria-live')).toBe('assertive');
    document.body.insertAdjacentHTML('beforeend', '<dialog open class="closing"></dialog>');
    announce('完了');
    advance(0);
    advance(60);
    expect(el('[aria-live]').textContent).toBe('新しい');
    el('dialog').classList.remove('closing');
    advance(60);
    advance(60);
    expect(el('dialog [aria-live]').textContent).toBe('完了');
    expect(document.querySelectorAll('[aria-live]')).toHaveLength(1);
});
